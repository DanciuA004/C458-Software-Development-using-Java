package com.mthree.java_basics.variables;

public class BestAdderEver {
    public static void main(String[] args) {
        int num1, num2, num3;
        int adder;

        num1 = 9;
        num2 = 4;
        num3 = 74;

        adder = num1 + num2 + num3;

        System.out.println(num1 + " + " + num2 + " + " + num3 + " = " + adder);

    }
}
